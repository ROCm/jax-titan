"""FlyDSL GEMMs in JAX through XLA's FFI, compiled ahead of time.

FlyDSL (https://github.com/ROCm/FlyDSL) compiles a kernel for one
specialization and exports it as a C object and header (`export_to_c`) that
need neither FlyDSL nor Python at run time. `build` exports FlyDSL's
preshuffle BF16 GEMM, C [M, N] = A [M, K] times B [N, K] transposed with B in
16x16 blocks, for each N x K given, writes an XLA FFI handler per kernel and
links them into one shared library with a JSON manifest beside it. With
JAX_TITAN_FLYDSL_LIB naming that library, the `flydsl` provider's `linear`
runs its forward and activation-gradient GEMMs on FlyDSL, shuffling the weight
into blocks for each, and its weight gradient on XLA, which would otherwise
need both of its operands transposed.

  python -m jax_titan.ops.providers.flydsl build OUT_DIR --shapes 4096x4096,14336x4096
  JAX_TITAN_FLYDSL_LIB=OUT_DIR/libjax_titan_flydsl.so python ... (ops policy linear=flydsl)

A [K_in, N_out] weight needs N_out x K_in (forward) and K_in x N_out (activation
gradient). The export needs FlyDSL's Python package (installed, or under
JAX_TITAN_FLYDSL_PKGS) and its source tree, for the kernels
(JAX_TITAN_FLYDSL_ROOT, default ../FlyDSL beside this repository), and runs in
a subprocess against a stand-in `torch` module: FlyDSL 0.5.0 imports PyTorch
only to register its types.
"""

import argparse
import ctypes
import functools
import json
import os
import pathlib
import shutil
import subprocess
import sys

import jax
import jax.numpy as jnp

from jax_titan.ops import registry
from jax_titan.ops.partitioned import partitioned
from jax_titan.ops.registry import Impl

_HERE = pathlib.Path(__file__).resolve().parent
_REPO = _HERE.parents[2]
LIB_ENV = "JAX_TITAN_FLYDSL_LIB"
M_MAX = 65536  # the kernel views A and C as M_MAX rows

_EXPORT = r"""
import json, sys
sys.path[:0] = json.loads(sys.argv[1])
import jax, jax.numpy as jnp
import flydsl.compiler as flyc
from kernels.gemm.preshuffle_gemm import compile_preshuffle_gemm
out, name = sys.argv[2], sys.argv[3]
n, k, tm, tn, tk = (int(v) for v in sys.argv[4:9])
launch = compile_preshuffle_gemm(N=n, K=k, tile_m=tm, tile_n=tn, tile_k=tk, in_dtype="bf16",
                                 out_dtype="bf16")
cpu = jax.devices("cpu")[0]
place = lambda size, dtype: flyc.from_dlpack(jax.device_put(jnp.zeros((size,), dtype), cpu))
args = [place(tm * n, jnp.bfloat16), place(tm * k, jnp.bfloat16), place(n * k, jnp.bfloat16),
        place(0, jnp.float32), place(0, jnp.float32), place(0, jnp.bfloat16)]
flyc.compile(launch, *args, tm, n, None).export_to_c(file_path=out, file_name=name)
"""

_PRELUDE = """// Generated by jax_titan.ops.providers.flydsl: XLA FFI handlers for FlyDSL GEMMs.
#include <string>
#include <hip/hip_runtime.h>
#include "xla/ffi/api/ffi.h"
namespace ffi = xla::ffi;
"""

_HANDLER = """
static ffi::Error {name}_ffi_impl(hipStream_t stream, ffi::Buffer<ffi::BF16> a,
                                  ffi::Buffer<ffi::BF16> b, ffi::ResultBuffer<ffi::BF16> c) {{
  int32_t status = {name}_call_auto(c->untyped_data(), a.untyped_data(), b.untyped_data(), nullptr,
                                    nullptr, nullptr, static_cast<int32_t>(a.dimensions()[0]), {n},
                                    stream);
  if (status != 0) return ffi::Error::Internal("FlyDSL {name}: status " + std::to_string(status));
  return ffi::Error::Success();
}}
XLA_FFI_DEFINE_HANDLER_SYMBOL({name}_ffi, {name}_ffi_impl, ffi::Ffi::Bind()
    .Ctx<ffi::PlatformStream<hipStream_t>>()
    .Arg<ffi::Buffer<ffi::BF16>>()
    .Arg<ffi::Buffer<ffi::BF16>>()
    .Ret<ffi::Buffer<ffi::BF16>>());
"""


def tiles(n: int, k: int, tile_m: int = 64) -> tuple[int, int, int]:
  """(tile_m, tile_n, tile_k): the widest N and K tiles FlyDSL's preshuffle GEMM takes."""
  tile_n = next((t for t in (256, 128, 64) if n % t == 0), None)
  tile_k = next((t for t in (128, 64) if k % t == 0), None)
  if tile_n is None or tile_k is None:
    raise ValueError(f"N {n} needs a multiple of 64 and K {k} of 64")
  return tile_m, tile_n, tile_k


def _rocm_root() -> pathlib.Path:
  if os.environ.get("ROCM_PATH"):
    return pathlib.Path(os.environ["ROCM_PATH"])
  out = subprocess.run(["rocm-sdk", "path", "--root"], capture_output=True, text=True, check=True)
  return pathlib.Path(out.stdout.strip())


def build(out_dir: str, shapes: list[tuple[int, int]], tile_m: int = 64) -> pathlib.Path:
  """Exports a kernel per (N, K) and links their FFI handlers into libjax_titan_flydsl.so."""
  out = pathlib.Path(out_dir).resolve()
  out.mkdir(parents=True, exist_ok=True)
  rocm = _rocm_root()
  paths = [str(_HERE / "_flydsl_torch_stub")]
  if os.environ.get("JAX_TITAN_FLYDSL_PKGS"):
    paths.append(os.environ["JAX_TITAN_FLYDSL_PKGS"])
  paths.append(os.environ.get("JAX_TITAN_FLYDSL_ROOT") or str(_REPO.parent / "FlyDSL"))
  env = dict(os.environ, ROCM_PATH=str(rocm), JAX_PLATFORMS="cpu",
             FLYDSL_GPU_ARCH=os.environ.get("FLYDSL_GPU_ARCH", "gfx942"),
             PATH=f"{rocm / 'llvm' / 'bin'}{os.pathsep}{os.environ.get('PATH', '')}")
  kernels = []
  for n, k in shapes:
    tm, tn, tk = tiles(n, k, tile_m)
    name = f"jax_titan_flydsl_n{n}_k{k}"
    subprocess.run([sys.executable, "-c", _EXPORT, json.dumps(paths), str(out), name, str(n), str(k),
                    str(tm), str(tn), str(tk)], env=env, check=True)
    kernels.append({"n": n, "k": k, "tile": [tm, tn, tk], "name": name, "handler": f"{name}_ffi"})
  source = out / "jax_titan_flydsl.cc"
  source.write_text(_PRELUDE + "".join(f'#include "{k["name"]}.h"\n' for k in kernels)
                    + "".join(_HANDLER.format(name=k["name"], n=k["n"]) for k in kernels))
  lib = out / "libjax_titan_flydsl.so"
  handlers = out / "jax_titan_flydsl_ffi.o"
  hipcc = shutil.which("hipcc") or str(rocm / "bin" / "hipcc")
  # Two steps: given sources, hipcc compiles every input as HIP, objects included.
  subprocess.run([hipcc, "-O2", "-std=c++17", "-fPIC", "-c", f"-I{jax.ffi.include_dir()}", f"-I{out}",
                  str(source), "-o", str(handlers)], check=True)
  subprocess.run([hipcc, "-shared", "-fPIC", str(handlers),
                  *(str(out / f"{k['name']}.o") for k in kernels), f"-L{rocm / 'lib'}", "-lamdhip64",
                  "-pthread", "-ldl", "-o", str(lib)], check=True)
  manifest = {"arch": env["FLYDSL_GPU_ARCH"], "kernels": kernels}
  lib.with_suffix(".json").write_text(json.dumps(manifest, indent=1) + "\n")
  return lib


@functools.cache
def kernels() -> dict:
  """{(N, K): FFI target} from the library JAX_TITAN_FLYDSL_LIB names, registered with JAX."""
  path = os.environ.get(LIB_ENV)
  if not path:
    raise RuntimeError(f"set {LIB_ENV} to a library from `python -m jax_titan.ops.providers.flydsl build`")
  lib = ctypes.cdll.LoadLibrary(path)
  out = {}
  for k in json.loads(pathlib.Path(path).with_suffix(".json").read_text())["kernels"]:
    target = k["name"]
    jax.ffi.register_ffi_target(target, jax.ffi.pycapsule(getattr(lib, k["handler"])),
                                platform="ROCM")
    out[(k["n"], k["k"])] = target
  return out


def shuffle(b):
  """[N, K] in FlyDSL's preshuffled 16x16 blocks (its shuffle_weight, 2-byte elements)."""
  n, k = b.shape
  return b.reshape(n // 16, 16, k // 32, 4, 8).transpose(0, 2, 3, 1, 4).reshape(n, k)


def gemm_shuffled(a, b_shuffled):
  """a [M, K] times b [N, K] transposed, b already in blocks (`shuffle`)."""
  (m, k), n = a.shape, b_shuffled.shape[0]
  return jax.ffi.ffi_call(kernels()[(n, k)], jax.ShapeDtypeStruct((m, n), a.dtype))(a, b_shuffled)


def _nt_local(a, b, params):
  del params
  return gemm_shuffled(a, shuffle(b))


_nt = partitioned(_nt_local, (("r", "k"), ("c", "k")), (("r", "c"),))


@jax.custom_vjp
def _linear_2d(x, w):
  return _nt(x, w.T, ())


def _linear_2d_fwd(x, w):
  return _linear_2d(x, w), (x, w)


def _linear_2d_bwd(residuals, dy):
  x, w = residuals
  dw = jax.lax.dot_general(x, dy, (((0,), (0,)), ((), ())))
  return _nt(dy, w, ()), dw.astype(w.dtype)


_linear_2d.defvjp(_linear_2d_fwd, _linear_2d_bwd)


def linear(x, w):
  y = _linear_2d(x.reshape(-1, x.shape[-1]), w.astype(x.dtype))
  return y.reshape(*x.shape[:-1], w.shape[-1])


def _linear_supports(x, w):
  if registry.under_vmap(x, w):
    return ("custom_partitioning has no batching rule, so it cannot run under jax.vmap; "
            "use --per_device=shard_map")
  if x.dtype != jnp.bfloat16 or w.ndim != 2:
    return f"needs bf16 x and a 2-D weight, not {x.dtype} and {w.ndim}-D"
  if x.size // x.shape[-1] > M_MAX:
    return f"more than {M_MAX} rows"
  k_in, n_out = w.shape
  missing = [s for s in ((n_out, k_in), (k_in, n_out)) if s not in kernels()]
  if missing:
    return f"no FlyDSL kernel for N x K {missing} in {os.environ.get(LIB_ENV)}"
  return None


def bf16():
  if jax.devices()[0].platform != "gpu":
    raise RuntimeError("FlyDSL kernels here run on ROCm GPUs")
  kernels()
  return {"linear": Impl(linear, "FlyDSL preshuffle BF16 GEMM (XLA weight gradient)",
                         _linear_supports)}


def main(argv=None):
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  sub = parser.add_subparsers(dest="cmd", required=True)
  p = sub.add_parser("build", help="Export kernels and link their FFI handlers.")
  p.add_argument("out_dir")
  p.add_argument("--shapes", required=True, help="Comma-separated N x K, such as 4096x14336.")
  p.add_argument("--tile_m", type=int, default=64)
  args = parser.parse_args(argv)
  shapes = [tuple(int(v) for v in s.lower().split("x")) for s in args.shapes.split(",")]
  print(build(args.out_dir, shapes, args.tile_m))
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
